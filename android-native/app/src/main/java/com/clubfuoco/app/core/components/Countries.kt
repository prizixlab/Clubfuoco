/**
 * Longest dial code first.
 *
 * Load-bearing for parsing a stored number: "+1" is a prefix of "+1..." but so
 * is nothing else, while "+34" and "+345" would both match a Spanish number if
 * tested in list order. Matching longest-first resolves the overlap the only way
 * that is correct.
 */
