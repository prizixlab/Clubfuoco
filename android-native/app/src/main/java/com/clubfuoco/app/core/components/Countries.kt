/**
 * A country code with its dialling prefix, flag, and the maximum number of
 * NATIONAL digits — the dial code excluded. The digit count caps input, which is
 * what stops someone typing their number twice into the same field.
 *
 * Generated from `PhoneNumberField.swift`'s list rather than retyped, so the two
 * platforms cannot drift. Regenerate if that list changes.
 */
data class Country(
    val name: String,
    val flag: String,
    val dialCode: String,
    val digits: Int,
) {
    val key: String get() = name + dialCode
}

private fun C(name: String, flag: String, dialCode: String, digits: Int) =
    Country(name, flag, dialCode, digits)

